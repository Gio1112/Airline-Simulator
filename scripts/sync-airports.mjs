import { access, writeFile } from "node:fs/promises";

const SOURCE = "https://davidmegginson.github.io/ourairports-data/airports.csv";
const OUTPUT = new URL("../src/game/generated-airports.ts", import.meta.url);

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];

    if (quoted) {
      if (char === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        field += char;
      }
      continue;
    }

    if (char === '"') {
      quoted = true;
    } else if (char === ",") {
      row.push(field);
      field = "";
    } else if (char === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (char !== "\r") {
      field += char;
    }
  }

  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }

  return rows;
}

function clean(value) {
  return String(value ?? "").trim();
}

async function keepFallback(error) {
  try {
    await access(OUTPUT);
    console.warn(`[airports] Sync failed; using committed fallback. ${error instanceof Error ? error.message : error}`);
  } catch {
    throw error;
  }
}

try {
  console.log(`[airports] Downloading ${SOURCE}`);
  const response = await fetch(SOURCE, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`OurAirports returned HTTP ${response.status}`);

  const rows = parseCsv(await response.text());
  if (rows.length < 2) throw new Error("OurAirports CSV was empty");

  const header = rows[0];
  const index = Object.fromEntries(header.map((name, position) => [name, position]));
  const at = (row, column) => clean(row[index[column]]);
  const byIata = new Map();

  for (const row of rows.slice(1)) {
    const type = at(row, "type");
    const scheduled = at(row, "scheduled_service") === "yes";
    const iata = at(row, "iata_code").toUpperCase();

    if (!/^[A-Z]{3}$/.test(iata)) continue;
    if (type !== "large_airport" && type !== "medium_airport") continue;
    if (type === "medium_airport" && !scheduled) continue;

    const lat = Number(at(row, "latitude_deg"));
    const lon = Number(at(row, "longitude_deg"));
    if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;

    const record = {
      iata,
      icao: at(row, "gps_code") || at(row, "ident"),
      city: at(row, "municipality") || at(row, "name"),
      name: at(row, "name"),
      country: at(row, "iso_country"),
      lat: Math.round(lat * 1_000_000) / 1_000_000,
      lon: Math.round(lon * 1_000_000) / 1_000_000,
      demand: type === "large_airport" ? 95 : 64,
      type,
    };

    const existing = byIata.get(iata);
    if (!existing || (existing.type !== "large_airport" && type === "large_airport")) {
      byIata.set(iata, record);
    }
  }

  const airports = [...byIata.values()].sort((a, b) => {
    if (a.type !== b.type) return a.type === "large_airport" ? -1 : 1;
    return a.iata.localeCompare(b.iata);
  });

  if (airports.length < 500) throw new Error(`Only ${airports.length} airports parsed; refusing suspicious dataset`);

  const moduleText = `import type { Airport } from "./types";\n\n// AUTO-GENERATED by scripts/sync-airports.mjs from the OurAirports public-domain dataset.\n// Do not edit by hand; the committed file doubles as an offline fallback.\nexport const generatedAirports: Airport[] = ${JSON.stringify(airports, null, 2)};\n`;
  await writeFile(OUTPUT, moduleText, "utf8");
  console.log(`[airports] Wrote ${airports.length.toLocaleString()} scheduled medium/large airports.`);
} catch (error) {
  await keepFallback(error);
}
